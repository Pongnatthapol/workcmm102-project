def calculate_ingredients(people_count):
    # base_recipeคือโครงสร้างข้อมูลสำหรับเก็บสูตรอาหารสำหรับ 1 คน
    base_recipe = {
        "ข้าวสาร (ถ้วยตวง)": 1,
        "ไข่ไก่ (ฟอง)": 2,
        "หมูสับ (กรัม)": 150,
        "น้ำซอส (ช้อนโต๊ะ)": 1.5
    }
    
    print("\n----------------------------------")
    # การจัดรูปแบบ Output ด้วย f-string
    print(f"ปริมาณวัตถุดิบสำหรับ {people_count} คน:")
    print("----------------------------------")
    
    # วนลูป (for loop) อ่านวัตถุดิบและคำนวณสัดส่วน
    for ingredient, amount in base_recipe.items():
        # การประมวลผลคำนวณสัดส่วน (Process)
        new_amount = amount * people_count
        
        # แสดงผลลัพธ์ กำหนดทศนิยม 1 ตำแหน่งด้วย {ตัวแปร:.1f}
        print(f"- {ingredient}: {new_amount:.1f}")
        
    print("----------------------------------\n")


