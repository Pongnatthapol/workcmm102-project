# 2. ฟังก์ชันหลักสำหรับรับค่าและตรวจสอบความถูกต้อง (Input & Error Handling)
# ---------------------------------------------------------
def main():
    print("=== โปรแกรมคำนวณสัดส่วนสูตรอาหาร ===")
    
    # วนถามซ้ำจนกว่าผู้ใช้จะกรอกข้อมูลถูกต้องด้วย while True
    while True:
        try:
            # รับข้อมูลนำเข้า (Input)
            user_input = input("กรุณากรอกจำนวนคน (ตัวเลขจำนวนเต็ม): ")
            
            # ตรวจสอบว่าผู้ใช้กรอกเฉพาะตัวเลขหรือไม่ด้วย .isdigit()
            if user_input.isdigit():
                people = int(user_input)
                
                # ตรวจสอบเงื่อนไขเชิงตรรกะด้วย if-else
                if people > 0:
                    # ข้อมูลถูกต้อง เรียกใช้ฟังก์ชันคำนวณ
                    calculate_ingredients(people)
                    break  # ออกจากลูปเมื่อคำนวณเสร็จ 
                else:
                    print("[ข้อผิดพลาด] จำนวนคนต้องมากกว่า 0\n")
            else:
                print("[ข้อผิดพลาด] กรุณากรอกเฉพาะตัวเลขจำนวนเต็มบวกเท่านั้น!\n")
                
        except ValueError:
            # ดักจับ Runtime Error (ValueError) ValueErrorคือการใส่ตัวอื่นที่ไม่ใช่ตัวเลข
            print("[ข้อผิดพลาด] เกิดข้อผิดพลาดในระบบ กรุณากรอกตัวเลขอีกครั้ง\n")


# เรียกใช้งานฟังก์ชันหลักของโปรแกรม
main()